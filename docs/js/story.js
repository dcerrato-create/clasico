// story.js - the "AI Story" card.
//
// The story is written by OpenAI on the backend and arrives piece by piece
// (see apiStream in api.js). This file shows it being typed, with a blinking
// cursor, and looks after the EN/ES toggle.
//
// To protect the OpenAI credits, the page only asks for a NEW story when the
// visitor did something (picked a rivalry, pressed a button). It cancels the
// request if they move on before the story is finished.

const STORY_DISCLAIMER =
  "Written by AI. The numbers come from our match data; the history comes from Wikipedia and the AI's own " +
  "knowledge. AI can make mistakes. Always verify key stats in the sections below.";

// Stories already shown during this visit: "Argentina|Brazil|es" -> { story, model, source }.
// (The backend has its own permanent cache; this just avoids repeat requests.)
const storyMemo = new Map();

let storyLang = "en";    // the language the visitor last chose
let storyRequest = null; // the AbortController of the story being fetched, if any
let storyRun = 0;        // goes up with every new story, so old ones know to stop

// Stop whatever story is being fetched or typed. Called when the visitor
// picks another rivalry.
function cancelStory() {
  storyRun++;
  if (storyRequest) storyRequest.abort();
  storyRequest = null;
}

// askFirst = true shows a "Write the AI Story" button instead of writing a
// new story straight away (used when the page opens from a shared link, so
// simply loading a page never spends credits).
function renderStory(container, data, { askFirst = false } = {}) {
  const teamA = data.team_a.name;
  const teamB = data.team_b.name;

  const card = makeEl("section", "card story");
  card.setAttribute("aria-labelledby", "story-heading");

  const head = makeEl("div", "story-head");
  const heading = makeEl("h2", "story-heading");
  heading.id = "story-heading";
  heading.append(makeEl("span", "ai-badge", "✦"), "AI Story");

  const toggle = makeEl("div", "lang-toggle");
  toggle.setAttribute("role", "group");
  toggle.setAttribute("aria-label", "Story language");
  const buttons = {};
  for (const [lang, label, title] of [["en", "EN", "English"], ["es", "ES", "Español"]]) {
    buttons[lang] = makeButton("", label, () => {
      storyLang = lang;
      load({ allowNew: true }); // the visitor asked for this language
    });
    buttons[lang].title = title;
    toggle.append(buttons[lang]);
  }
  head.append(heading, toggle);

  // The story text: the words typed so far, then the blinking cursor.
  const text = makeEl("p", "story-text");
  text.setAttribute("aria-live", "polite");
  const words = makeEl("span", "story-words");
  const cursor = makeEl("span", "story-cursor");
  cursor.setAttribute("aria-hidden", "true");
  text.append(words, cursor);

  // "Generated by gpt-5.4 · History source: Wikipedia, <article>"
  const modelLabel = makeEl("p", "story-model");
  const disclaimer = makeEl("p", "story-disclaimer");
  disclaimer.append(makeEl("span", "story-disclaimer-icon", "!"), STORY_DISCLAIMER);

  card.append(head, text, modelLabel, disclaimer);
  container.append(card);

  // The toggle is switched off while a story is being written.
  function setToggle(enabled) {
    for (const [lang, button] of Object.entries(buttons)) {
      button.disabled = !enabled;
      button.setAttribute("aria-pressed", String(lang === storyLang));
    }
    toggle.classList.toggle("busy", !enabled);
  }

  // Show a message in place of the story, with one button under it.
  function showMessage(message, buttonLabel, onClick, isError) {
    text.className = isError ? "story-text story-error" : "story-text story-offer";
    const button = makeButton(isError ? "secondary" : "primary story-write", buttonLabel, onClick);
    text.replaceChildren(message ? `${message} ` : "", button);
    modelLabel.textContent = "";
    setToggle(true);
  }

  async function load({ allowNew }) {
    cancelStory(); // stop any story that is still being fetched or typed
    const run = storyRun;
    const lang = storyLang;
    const memoKey = [teamA, teamB].sort().join("|") + "|" + lang;

    // --- "AI is writing…" until the first words arrive ---
    setToggle(false);
    text.className = "story-text writing";
    text.lang = lang;
    words.textContent = lang === "es" ? "La IA está escribiendo" : "AI is writing";
    text.replaceChildren(words, cursor);
    modelLabel.textContent = "";

    let received = "";      // all the text that has arrived so far
    let shown = 0;          // how many characters are on screen
    let complete = false;   // has the whole story arrived?
    let model = "";
    let source = null;      // the Wikipedia article used for the history, if any
    let fast = false;       // saved stories type out faster than live ones

    function finish() {
      text.className = "story-text"; // hides the cursor
      // Say which model wrote it and where the history came from.
      modelLabel.replaceChildren(`Generated by ${model} · `);
      if (source) {
        const link = makeEl("a", "", source.title);
        link.href = source.url;
        link.target = "_blank";
        link.rel = "noopener";
        modelLabel.append("History source: Wikipedia, ", link);
      } else {
        modelLabel.append("History from the AI's own knowledge (no Wikipedia article found)");
      }
      storyMemo.set(memoKey, { story: received, model, source });
      setToggle(true);
    }

    // Reveals the text a few characters per frame, like typing. A live story
    // speeds up a little when it falls behind what has already arrived.
    function type() {
      if (run !== storyRun || !card.isConnected) return; // this story was cancelled
      if (received.length > 0 && shown === 0) text.className = "story-text typing";
      if (shown < received.length) {
        const behind = received.length - shown;
        const step = reducedMotion ? behind : fast ? 6 : Math.max(1, Math.ceil(behind / 40));
        shown = Math.min(received.length, shown + step);
        words.textContent = received.slice(0, shown);
      }
      if (complete && shown >= received.length) {
        finish();
        return;
      }
      requestAnimationFrame(type);
    }

    // A story we already have from earlier in this visit: no request at all.
    if (storyMemo.has(memoKey)) {
      ({ story: received, model, source } = storyMemo.get(memoKey));
      complete = true;
      fast = true;
      requestAnimationFrame(type);
      return;
    }

    storyRequest = new AbortController();
    let failure = null; // an error the backend reported halfway through
    try {
      const plainAnswer = await apiStream(
        "/api/story",
        { team_a: teamA, team_b: teamB, lang, cached_only: !allowNew },
        storyRequest.signal,
        (event) => {
          if (event.type === "start") {
            model = event.model;
            source = event.source;
            fast = event.cached;
            requestAnimationFrame(type);
          } else if (event.type === "text") {
            received += event.text;
          } else if (event.type === "done") {
            complete = true;
          } else if (event.type === "error") {
            failure = event.message;
          }
        }
      );
      if (run !== storyRun) return;

      // We only asked "is it saved?" and it isn't: offer to write it.
      if (plainAnswer && plainAnswer.cached === false) {
        showMessage("", "✦ Write the AI Story", () => load({ allowNew: true }), false);
        return;
      }
      if (failure) throw new ApiError(failure);
      // The connection closed before the backend said "done": don't keep half a story.
      if (!complete) throw new ApiError("The story was cut off before it finished. Please try again.");
    } catch (err) {
      if (err.name === "AbortError" || run !== storyRun || !card.isConnected) return; // cancelled on purpose
      storyRun++; // stops the typing loop
      showMessage(err.message, "Try again", () => load({ allowNew: true }), true);
    }
  }

  load({ allowNew: !askFirst });
}
